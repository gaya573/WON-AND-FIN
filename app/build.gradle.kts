// Signing credentials live outside version control. Without the file the release
// build is unsigned, which fails fast instead of shipping a debug-keyed APK.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

android {
    namespace = "com.windergoodlife.smsrelay"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.windergoodlife.smsrelay"
        minSdk = 26
        targetSdk = 36
        versionCode = 10
        versionName = "1.0.9"
        buildConfigField("String", "DEFAULT_BASE_URL", "\"https://chat.dealerhub.co.kr\"")
    }

    signingConfigs {
        if (keystoreProperties.getProperty("storeFile") != null) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            signingConfig = signingConfigs.findByName("release")
        }
        debug {
            // Cleartext still blocked via network security config.
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        viewBinding = true
        buildConfig = true
    }
    testOptions.unitTests.isReturnDefaultValues = true
}

